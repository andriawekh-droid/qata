from datetime import datetime
from flask import g

SUPPORTED_LANGS = ('id', 'en')
DEFAULT_LANG = 'id'
LANG_COOKIE = 'qata_lang'

MONTHS_ID = {
    1: 'Jan', 2: 'Feb', 3: 'Mar', 4: 'Apr', 5: 'Mei', 6: 'Jun',
    7: 'Jul', 8: 'Agu', 9: 'Sep', 10: 'Okt', 11: 'Nov', 12: 'Des',
}
MONTHS_EN = {
    1: 'Jan', 2: 'Feb', 3: 'Mar', 4: 'Apr', 5: 'May', 6: 'Jun',
    7: 'Jul', 8: 'Aug', 9: 'Sep', 10: 'Oct', 11: 'Nov', 12: 'Dec',
}


def detect_lang(req):
    """Deteksi bahasa: Cookie manual -> Cloudflare CF-IPCountry -> Accept-Language -> default 'id'."""
    cookie_lang = (req.cookies.get(LANG_COOKIE) or '').strip().lower()
    if cookie_lang in SUPPORTED_LANGS:
        return cookie_lang

    cf_country = (req.headers.get('CF-IPCountry') or '').strip().upper()
    if cf_country and cf_country not in ('XX', 'T1'):
        return 'id' if cf_country == 'ID' else 'en'

    best = req.accept_languages.best_match(list(SUPPORTED_LANGS))
    if best in SUPPORTED_LANGS:
        return best

    return DEFAULT_LANG


def get_lang():
    try:
        lang = getattr(g, 'lang', DEFAULT_LANG)
        return lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    except RuntimeError:
        return DEFAULT_LANG


def t(key, **kwargs):
    lang = get_lang()
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def format_date_localized(value, lang=None):
    if value is None:
        return ''
    lang = lang or get_lang()
    months = MONTHS_EN if lang == 'en' else MONTHS_ID
    try:
        if hasattr(value, 'strftime'):
            dt_obj = value
        else:
            s = str(value)
            dt_obj = datetime.strptime(s[:10], '%Y-%m-%d')
        return f"{dt_obj.day:02d} {months[dt_obj.month]} {dt_obj.year}"
    except Exception:
        return str(value)[:10]


def format_relative_time_localized(value, lang=None):
    if value is None:
        return ''
    lang = lang or get_lang()
    try:
        if hasattr(value, 'strftime'):
            dt_obj = value
        else:
            s = str(value)
            dt_obj = datetime.strptime(s[:19], '%Y-%m-%d %H:%M:%S')
    except Exception:
        return str(value)[:10]

    now = datetime.now()
    detik = (now - dt_obj).total_seconds()

    if detik < 60:
        return 'Just now' if lang == 'en' else 'Baru saja'
    elif detik < 3600:
        menit = int(detik // 60)
        return f'{menit} min ago' if lang == 'en' else f'{menit} menit yang lalu'
    elif detik < 86400:
        jam = int(detik // 3600)
        return f'{jam} hr ago' if lang == 'en' else f'{jam} jam yang lalu'
    elif detik < 604800:
        hari = int(detik // 86400)
        return f'{hari}d ago' if lang == 'en' else f'{hari} hari yang lalu'
    else:
        return format_date_localized(dt_obj, lang=lang)


def format_money(amount, currency='IDR'):
    cur = (currency or 'IDR').upper()
    if cur == 'USD':
        try:
            val = float(amount or 0)
        except (TypeError, ValueError):
            val = 0.0
        if val.is_integer():
            return f"${int(val):,}"
        return f"${val:,.2f}"
    try:
        nominal = int(float(amount or 0))
    except (TypeError, ValueError):
        nominal = 0
    return f"Rp{nominal:,}".replace(',', '.')


